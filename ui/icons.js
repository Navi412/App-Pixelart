// --- Iconos dibujados como texto: '#' = píxel encendido, cualquier otro = vacío ---

function art(rows) {
  const cells = [];
  rows.forEach((row, y) => [...row].forEach((ch, x) => ch === '#' && cells.push([x, y])));
  return svg(cells);
}

const flipRows = (rows) => [...rows].reverse();
const transpose = (rows) => rows[0].split('').map((_, x) => rows.map((row) => row[x]).join(''));

